#!/bin/bash
set -euo pipefail
cd "$(dirname "$0")/.."
test "$(uname -m)" = x86_64
export MACOSX_DEPLOYMENT_TARGET=14.0
ROOT="$PWD"
APP="$ROOT/dist/AmuMusic Audio Separator.app"
RES="$APP/Contents/Resources"
mkdir -p "$APP/Contents/MacOS" "$RES/app"

# uv uses relocatable python-build-standalone; never copy setup-python's framework.
uv python install 3.12
BASE_PY="$(uv python find --managed-python 3.12)"
# sphn's bundled Opus source predates CMake 4's removed compatibility policy.
# Build tool stays outside the shipped application runtime.
uv tool install --python "$BASE_PY" cmake==3.31.6
export CMAKE="$(uv tool dir)/cmake/bin/cmake"
PREFIX="$($BASE_PY -c 'import sys; print(sys.prefix)')"
ditto "$PREFIX" "$RES/runtime"
PY="$RES/runtime/bin/python3"
# This is our private copied runtime, not the runner's managed interpreter.
uv pip install --break-system-packages --python "$PY" -r build/requirements-intel.txt
uv pip check --python "$PY"
uv pip freeze --python "$PY" > dist/dependencies-intel.txt

# Intel samplerate wheel already contains a native dylib; bundle-local loading only.
SAMPLE_LIB="$("$PY" -c "import importlib.util,pathlib; print(pathlib.Path(importlib.util.find_spec('samplerate').origin).parent/'_samplerate_data/libsamplerate.dylib')")"
lipo "$SAMPLE_LIB" -verify_arch x86_64
"$PY" - "$SAMPLE_LIB" <<'PY'
import importlib.util,pathlib,shutil,sys
package=pathlib.Path(importlib.util.find_spec('samplerate').origin).parent
# Keep the wheel-provided native Intel library.
loader=package/'lowlevel.py'
code=loader.read_text()
old="lib_filename = _find_library('samplerate')"
assert old in code
code=code.replace(old,"lib_filename = _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), '_samplerate_data', 'libsamplerate.dylib')")
loader.write_text(code)
import samplerate,numpy as np
assert len(samplerate.resample(np.zeros(100,dtype='float32'),0.5)) == 50
PY

ditto app "$RES/app"
ditto licenses "$RES/licenses"

"$PY" - "$RES/licenses/python-packages" <<'PY'
import importlib.metadata,pathlib,shutil,sys
dest=pathlib.Path(sys.argv[1])
for d in importlib.metadata.distributions():
 folder=dest/(d.metadata['Name']+'-'+d.version);folder.mkdir(parents=True,exist_ok=True)
 (folder/'METADATA.txt').write_text(d.read_text('METADATA') or '',encoding='utf-8')
 for f in d.files or []:
  if any(t in f.name.upper() for t in ('LICENSE','COPYING','NOTICE')):
   source=pathlib.Path(d.locate_file(f))
   if source.is_file():shutil.copy2(source,folder/f.name)
PY
mkdir -p "$RES/app/bin"
"$PY" - "$RES/app/bin/ffmpeg" <<'PY'
import imageio_ffmpeg,shutil,sys,os
shutil.copy2(imageio_ffmpeg.get_ffmpeg_exe(), sys.argv[1])
os.chmod(sys.argv[1],0o755)
PY
# Console scripts generated by installers contain the runner's build path.
# Our CLI fallback calls this wrapper, which resolves its own runtime at launch.
cat > "$RES/runtime/bin/demucs" <<'SH'
#!/bin/sh
exec "$(dirname "$0")/python3" -m demucs "$@"
SH
chmod +x "$RES/runtime/bin/demucs"

mkdir -p dist/AppIcon.iconset
for size in 16 32 128 256 512; do
  sips -z "$size" "$size" build/icon.png --out "dist/AppIcon.iconset/icon_${size}x${size}.png" >/dev/null
  twice=$((size * 2))
  sips -z "$twice" "$twice" build/icon.png --out "dist/AppIcon.iconset/icon_${size}x${size}@2x.png" >/dev/null
done
iconutil -c icns dist/AppIcon.iconset -o "$RES/AppIcon.icns"
xcrun swiftc -O -framework Cocoa -target x86_64-apple-macos14.0 build/Launcher.swift -o "$APP/Contents/MacOS/AmuMusic"
"$PY" - "$APP/Contents/Info.plist" <<'PY'
import plistlib,sys
with open(sys.argv[1],'wb') as f:
 plistlib.dump({'CFBundleExecutable':'AmuMusic','CFBundleIdentifier':'com.amumusic.audio-separator',
 'CFBundleName':'AmuMusic Audio Separator','CFBundleDisplayName':'Amu 音频分离',
 'CFBundleVersion':'2.0.0','CFBundleShortVersionString':'2.0.0','CFBundlePackageType':'APPL',
 'CFBundleIconFile':'AppIcon','NSHighResolutionCapable':True,'LSMinimumSystemVersion':'14.0'},f)
PY

# Validate after relocation to a Unicode path, like a user's Applications folder.
MOVED="$ROOT/dist/迁移验证/AmuMusic Audio Separator.app"
mkdir -p "$(dirname "$MOVED")"
mv "$APP" "$MOVED"
"$MOVED/Contents/Resources/runtime/bin/python3" build/smoke.py "$MOVED/Contents/Resources" dist/smoke-intel.json
mv "$MOVED" "$APP"
"$PY" build/verify_intel_bundle.py "$APP"
# Sign nested Mach-O files first; ad-hoc signing is not Apple notarization.
find "$APP" -type f -print0 | while IFS= read -r -d '' file; do
  if /usr/bin/file -b "$file" | grep -q 'Mach-O'; then codesign --force --sign - "$file"; fi
done
codesign --force --deep --sign - "$APP"
codesign --verify --deep --strict "$APP"
cp dist/dependencies-intel.txt "$RES/licenses/" # include dependency versions, then reseal resources
codesign --force --deep --sign - "$APP"
codesign --verify --deep --strict "$APP"
chmod -R a-w "$APP"
"$PY" build/native_smoke.py "$APP" dist/native-smoke-intel.json
chmod -R u+w "$APP"
cp build/使用说明_Intel.txt dist/instructions-intel.txt
ditto -c -k --sequesterRsrc --keepParent "$APP" dist/AmuMusic-macOS-Intel.zip
(cd dist && shasum -a 256 AmuMusic-macOS-Intel.zip > SHA256.txt)
